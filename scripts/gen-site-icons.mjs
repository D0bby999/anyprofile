// Writes frontend/src/sites/icons.gen.ts from an unpacked simple-icons package,
// keeping only the icons internal/site/catalog.json uses. Icons simple-icons no
// longer ships come from scripts/site-icons-extra (sources in its LICENSE.txt).
// Usage: node scripts/gen-site-icons.mjs <unpacked simple-icons package dir>
import fs from 'node:fs'
import path from 'node:path'

const pkg = process.argv[2]
if (!pkg) {
  console.error('usage: node scripts/gen-site-icons.mjs <simple-icons package dir>')
  process.exit(2)
}
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
const extra = path.join(root, 'scripts/site-icons-extra')
const { version } = JSON.parse(fs.readFileSync(path.join(pkg, 'package.json'), 'utf8'))
const catalog = JSON.parse(fs.readFileSync(path.join(root, 'internal/site/catalog.json'), 'utf8'))
const slugs = [...new Set(catalog.map((s) => s.icon).filter(Boolean))].sort()

const entries = slugs.map((slug) => {
  const own = path.join(pkg, 'icons', `${slug}.svg`)
  const svg = fs.readFileSync(fs.existsSync(own) ? own : path.join(extra, `${slug}.svg`), 'utf8')
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1] ?? '0 0 24 24'
  const d = [...svg.matchAll(/<path[^>]* d="([^"]+)"/g)].map((m) => m[1]).join(' ')
  if (!d) throw new Error(`no path in ${slug}.svg`)
  return `  ${JSON.stringify(slug)}: { viewBox: ${JSON.stringify(viewBox)}, d: ${JSON.stringify(d)} },`
})

const out = `// SPDX-License-Identifier: AGPL-3.0-or-later
// Generated by scripts/gen-site-icons.mjs from simple-icons ${version} and scripts/site-icons-extra. Do not edit.
// The icon paths are CC0-1.0 (LICENSE-simple-icons.txt) or MIT (LICENSE-extra-icons.txt).
// Brand marks identify a platform only; they are not AnyProfile's marks.
export const siteIcons: Record<string, { viewBox: string; d: string }> = {
${entries.join('\n')}
}
`
const dest = path.join(root, 'frontend/src/sites/icons.gen.ts')
fs.mkdirSync(path.dirname(dest), { recursive: true })
fs.writeFileSync(dest, out)
fs.copyFileSync(path.join(pkg, 'LICENSE.md'), path.join(root, 'frontend/src/sites/LICENSE-simple-icons.txt'))
fs.copyFileSync(path.join(extra, 'LICENSE.txt'), path.join(root, 'frontend/src/sites/LICENSE-extra-icons.txt'))
console.log(`wrote ${slugs.length} icons to ${path.relative(root, dest)}`)
