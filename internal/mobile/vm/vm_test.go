// gptWith builds a GPT header and table with the named partitions.
func gptWith(parts map[string][2]uint64) []byte {
	b := make([]byte, gptHeader)
	copy(b[sector:], "EFI PART")
	binary.LittleEndian.PutUint64(b[sector+72:], 2)
	binary.LittleEndian.PutUint32(b[sector+80:], 128)
	binary.LittleEndian.PutUint32(b[sector+84:], 128)
	i := 0
	for name, r := range parts {
		e := b[2*sector+i*128:]
		binary.LittleEndian.PutUint64(e[32:], r[0])
		binary.LittleEndian.PutUint64(e[40:], r[1])
		for j, u := range utf16.Encode([]rune(name)) {
			binary.LittleEndian.PutUint16(e[56+2*j:], u)
		}
		i++
	}
	return b
}

func TestPartition(t *testing.T) {
	gpt := gptWith(map[string][2]uint64{"super": {100, 199}, "persist": {9609216, 9641983}})
	first, n, err := partition(gpt, "persist")
	if err != nil || first != 9609216 || n != 32768 {
		t.Fatalf("persist = %d %d %v", first, n, err)
	}
	if _, _, err := partition(gpt, "boot"); err == nil {
		t.Fatal("found a partition that is not there")
	}
	if _, _, err := partition(make([]byte, gptHeader), "persist"); err == nil {
		t.Fatal("read a disk without GPT")
	}
}

// The block as LineageOS ships it (read from the image on 2026-10-23).
const shipped = grubSig + `# WARNING: Do not edit this file by tools other than grub-editenv!!!
android_insecure_adb=0
android_wifi_impl=
grub_android_default=0
grub_timeout=10
zram=0
`

func TestGrubenvRoundTrip(t *testing.T) {
	block := []byte(shipped + strings.Repeat("#", grubSize-len(shipped)))
	comments, env, err := parseGrubenv(block)
	if err != nil {
		t.Fatal(err)
	}
	if len(comments) != 1 || env["grub_timeout"] != "10" || env["zram"] != "0" {
		t.Fatalf("parsed %v %v", comments, env)
	}
	for k, v := range grubDefaults {
		env[k] = v
	}
	out, err := renderGrubenv(comments, env)
	if err != nil {
		t.Fatal(err)
	}
	if len(out) != grubSize || !strings.HasPrefix(string(out), grubSig+comments[0]+"\n") {
		t.Fatalf("rendered %q", out[:80])
	}
	_, again, _ := parseGrubenv(out)
	if again["android_insecure_adb"] != "1" || again["android_wifi_impl"] != "none arm64.nobti" || again["zram"] != "0" {
		t.Fatalf("reparsed %v", again)
	}
	if _, err := renderGrubenv(nil, map[string]string{"a": "b\nc=d"}); err == nil {
		t.Fatal("rendered a value with a newline")
	}
	if _, err := renderGrubenv(nil, map[string]string{"a": strings.Repeat("x", grubSize)}); err == nil {
		t.Fatal("rendered past 1024 bytes")
	}
	if _, _, err := parseGrubenv([]byte("not grub")); err == nil {
		t.Fatal("parsed something that is not grubenv")
	}
}

