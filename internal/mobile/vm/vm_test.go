func TestLocaleScript(t *testing.T) {
	line, err := localeScript("Asia/Tokyo", "ja-JP", []string{"com.zhiliaoapp.musically", "bad;rm -rf /", browserPkg})
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"cmd alarm set-timezone Asia/Tokyo",
		"cmd locale set-app-locales com.zhiliaoapp.musically --locales ja-JP",
		"cmd locale set-app-locales org.lineageos.jelly --locales ja-JP"} {
		if !strings.Contains(line, want) {
			t.Errorf("missing %q in %q", want, line)
		}
	}
	if strings.Contains(line, "rm -rf") {
		t.Fatalf("a bad package name reached the shell: %q", line)
	}
	for _, tc := range [][2]string{{"Asia/Tokyo; reboot", "en-US"}, {"UTC", "en-US$(id)"}, {"../x", ""}} {
		if _, err := localeScript(tc[0], tc[1], nil); err == nil {
			t.Errorf("%q %q accepted", tc[0], tc[1])
		}
	}
	if line, _ := localeScript("", "", nil); line != "" {
		t.Fatalf("nothing to set gave %q", line)
	}
}

func TestLocate(t *testing.T) {
	root := t.TempDir()
	code := func(err error) string {
		var ae *apperr.Error
		errors.As(err, &ae)
		return ae.Code
	}
	if _, err := Locate(root); code(err) != "android_runtime_missing" {
		t.Fatalf("empty: %v", err)
	}
	for _, f := range []string{"bin/qemu-system-aarch64", "bin/qemu-img", "share/edk2-aarch64-code.fd",
		"share/edk2-arm-vars.fd", "bin/adb", "bin/scrcpy", "share/scrcpy-server"} {
		p := filepath.Join(root, "qemu", f)
		os.MkdirAll(filepath.Dir(p), 0o700)
		os.WriteFile(p, nil, 0o700)
	}
	if _, err := Locate(root); code(err) != "android_image_missing" {
		t.Fatalf("no image: %v", err)
	}
	os.MkdirAll(filepath.Join(root, "image", "23.2"), 0o700)
	os.WriteFile(filepath.Join(root, "image", "CURRENT"), []byte("../../etc\n"), 0o600)
	if _, err := Locate(root); code(err) != "android_image_missing" {
		t.Fatalf("a path in CURRENT: %v", err)
	}
	os.WriteFile(filepath.Join(root, "image", "CURRENT"), []byte("23.2\n"), 0o600)
	for _, f := range []string{"vda.qcow2", "vdb.qcow2"} {
		os.WriteFile(filepath.Join(root, "image", "23.2", f), nil, 0o600)
	}
	rt, err := Locate(root)
	if err != nil || rt.ImageVersion != "23.2" {
		t.Fatalf("%+v %v", rt, err)
	}
}

// A QMP server: greeting, capabilities, then one command.
func TestQMP(t *testing.T) {
	sock := filepath.Join(t.TempDir(), "q")
	ln, err := net.Listen("unix", sock)
	if err != nil {
		t.Fatal(err)
	}
	defer ln.Close()
	go func() {
		c, err := ln.Accept()
		if err != nil {
			return
		}
		defer c.Close()
		r := bufio.NewReader(c)
		c.Write([]byte(`{"QMP":{"version":{}}}` + "\n"))
		r.ReadBytes('\n')
		c.Write([]byte(`{"return":{}}` + "\n"))
		line, _ := r.ReadBytes('\n')
		var m map[string]any
		json.Unmarshal(line, &m)
		if m["execute"] != "query-status" {
			c.Write([]byte(`{"error":{"class":"x","desc":"unexpected"}}` + "\n"))
			return
		}
		c.Write([]byte(`{"event":"RESUME"}` + "\n" + `{"return":{"status":"running","running":true}}` + "\n"))
	}()
	st, err := qmpStatus(context.Background(), sock)
	if err != nil || st != "running" {
		t.Fatalf("%q %v", st, err)
	}
}

func TestCloneOrCopy(t *testing.T) {
	dir := t.TempDir()
	src := filepath.Join(dir, "a")
	os.WriteFile(src, []byte("disk"), 0o600)
	if err := cloneOrCopy(src, filepath.Join(dir, "b")); err != nil {
		t.Fatal(err)
	}
	if b, _ := os.ReadFile(filepath.Join(dir, "b")); string(b) != "disk" {
		t.Fatalf("%q", b)
	}
	if err := cloneOrCopy(src, filepath.Join(dir, "b")); err == nil {
		t.Fatal("overwrote an existing file")
	}
}
